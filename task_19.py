import re
text = ('Звоните: +7 999 123-45-67 или 8 (912) 555-12-34. '
        'Офис: +7 (495) 765-43-21, склад: 8 800 100-20-30. '
        'Не номера: 8-999-123-45-67, +7 9991234567, +7 (999 123-45-67, '
        '88 999 111-22-33, 8 999 111-22-334.')
numbers = re.findall(r'(?<![\d+])(?:\+7|8) (?:\(\d{3}\)|\d{3}) \d{3}-\d{2}-\d{2}(?!\d)', text)
for number in numbers:
    print(number)